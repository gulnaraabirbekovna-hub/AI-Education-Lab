import streamlit as st

st.set_page_config(
    page_title="8 критериев проекта",
    page_icon="🏆",
    layout="wide"
)

st.title("🏆 8 критериев проекта AI Education Lab")

st.write(
    "Данный раздел представляет проект по восьми основным критериям "
    "оценки AI/ML-проекта."
)

# 1. Постановка задачи
with st.expander("1️⃣ Постановка задачи", expanded=True):
    st.markdown("""
    ### 🎯 Постановка задачи

    **Проблема:**  
    Показать, как данные об учебной деятельности могут использоваться
    для демонстрации возможностей машинного обучения.

    **Цель проекта:**  
    Создать учебный прототип, который на основе часов подготовки
    и посещаемости прогнозирует категорию результата.

    **Задача:**  
    Использовать Python и алгоритм Random Forest для построения
    демонстрационной ML-модели.
    """)

# 2. Подготовка данных
with st.expander("2️⃣ Подготовка данных"):
    st.markdown("""
    ### 📊 Подготовка данных

    Для проекта используется учебный набор данных.

    Основные признаки:

    - ⏱️ **hours** — часы подготовки;
    - 📅 **attendance** — посещаемость;
    - 🎯 **result** — категория результата.

    Категории результата:

    - Низкий
    - Средний
    - Высокий

    Для обработки данных используется библиотека **Pandas**.
    """)

# 3. Анализ и визуализация
with st.expander("3️⃣ Анализ и визуализация"):
    st.markdown("""
    ### 📈 Анализ и визуализация

    В проекте анализируется взаимосвязь между:

    - количеством часов подготовки;
    - посещаемостью;
    - результатом обучения.

    Для визуального представления используется точечная диаграмма.

    Визуализация позволяет увидеть распределение учебных результатов
    и наглядно представить исходные данные.
    """)

# 4. Корректность модели
with st.expander("4️⃣ Корректность модели"):
    st.markdown("""
    ### 🤖 Корректность модели

    В проекте используется алгоритм:

    **Random Forest Classifier**

    Модель обучается на двух признаках:

    - `hours` — часы подготовки;
    - `attendance` — посещаемость.

    Используется:

    - `n_estimators = 100`
    - `random_state = 42`

    Модель используется как учебная демонстрация и не предназначена
    для реального оценивания школьников.
    """)

# 5. Метрики и результаты
with st.expander("5️⃣ Метрики и результаты"):
    st.markdown("""
    ### 📏 Метрики и результаты

    Модель позволяет получить:

    - 🤖 прогноз категории результата;
    - 📊 вероятность принадлежности к каждой категории;
    - 📈 визуальное представление данных.

    Пользователь может изменять параметры в ML-лаборатории
    и наблюдать изменение прогноза.
    """)

# 6. Реализация прототипа
with st.expander("6️⃣ Реализация прототипа"):
    st.markdown("""
    ### 💻 Реализация прототипа

    Проект реализован с использованием:

    - 🐍 **Python** — программирование;
    - 📊 **Pandas** — обработка данных;
    - 📈 **Matplotlib** — визуализация;
    - 🤖 **Scikit-learn** — машинное обучение;
    - 🌐 **Streamlit** — создание веб-приложения.

    Пользователь может взаимодействовать с ML-моделью
    через интерактивные элементы Streamlit.
    """)

# 7. Отчёт и презентация
with st.expander("7️⃣ Отчёт и презентация"):
    st.markdown("""
    ### 📑 Отчёт и презентация

    Проект демонстрирует полный цикл работы:

    **Постановка задачи → Подготовка данных → Анализ →
    Модель → Прогноз → Результаты → Вывод**

    Интерактивный Streamlit-прототип позволяет представить
    результаты проекта во время защиты.

    Проект также может быть дополнен презентацией, отчётом,
    графиками и демонстрацией работы модели.
    """)

# 8. Этические и устойчивые аспекты
with st.expander("8️⃣ Этические и устойчивые аспекты"):
    st.markdown("""
    ### ⚖️ Этические и устойчивые аспекты

    **Конфиденциальность**

    При работе с реальными данными необходимо защищать
    персональную информацию учащихся.

    **Справедливость**

    Необходимо учитывать качество и возможную предвзятость данных.

    **Ответственность**

    Нельзя принимать педагогические решения только
    на основании прогноза искусственного интеллекта.

    **Роль учителя**

    Учитель сохраняет контроль над окончательным
    педагогическим решением.

    **Устойчивое использование ИИ**

    ИИ должен использоваться как инструмент поддержки обучения,
    а не как замена учителя.

    **Важно:** данные основного проекта являются учебными
    и демонстрационными.
    """)

